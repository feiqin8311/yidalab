export const resolveBuildProfile = (raw?: string): BuildProfile =>
  (raw || 'full').toLowerCase().trim() === 'internal' ? 'internal' : 'full';

export function discoverBackendRouteEntries(root: string): ProfileEntry[] {
  const backendRoot = path.join(root, 'src/app/(backend)');
  if (!fs.existsSync(backendRoot)) return [];

  const out: ProfileEntry[] = [];
  const walk = (dir: string) => {
    for (const name of fs.readdirSync(dir, { withFileTypes: true })) {
      const abs = path.join(dir, name.name);
      if (name.isDirectory()) {
        walk(abs);
        continue;
      }
      if (name.name !== 'route.full.ts') continue;
      const internalAbs = path.join(dir, 'route.internal.ts');
      if (!fs.existsSync(internalAbs)) {
        throw new Error(`applyBuildProfile: missing route.internal.ts next to ${abs}`);
      }
      out.push({
        entry: path.relative(root, path.join(dir, 'route.ts')),
        full: './route.full',
        internal: './route.internal',
      });
    }
  };
  walk(backendRoot);
  return out.sort((a, b) => a.entry.localeCompare(b.entry));
}

export function listAllProfileEntries(root: string): ProfileEntry[] {
  return [...CORE_PROFILE_ENTRIES, ...discoverBackendRouteEntries(root)];
}

export function renderProfileEntry(entry: ProfileEntry, profile: BuildProfile): string {
  const reexport = profile === 'internal' ? entry.internal : entry.full;
  return `/* AUTO-GENERATED by scripts/applyBuildProfile.ts — do not edit.
 * profile=${profile}
 */
export * from '${reexport}';
`;
}

export function applyBuildProfile(root: string, profile: BuildProfile): ProfileEntry[] {
  const all = listAllProfileEntries(root);
  for (const e of all) {
    const abs = path.join(root, e.entry);
    const dir = path.dirname(abs);
    const reexport = profile === 'internal' ? e.internal : e.full;
    const candidates = [
      path.join(dir, reexport.replace(/^\.\//, '') + (e.kind === 'tsx' ? '.tsx' : '.ts')),
      path.join(dir, reexport.replace(/^\.\//, '') + '.ts'),
      path.join(dir, reexport.replace(/^\.\//, '') + '.tsx'),
    ];
    if (!candidates.some((c) => fs.existsSync(c))) {
      throw new Error(`applyBuildProfile: missing ${reexport} for ${e.entry}`);
    }
    fs.writeFileSync(abs, renderProfileEntry(e, profile));
  }
  return all;
}

/** Exact match against the canonical generated re-export body. */
export function entryPointsToProfile(
  entryBody: string,
  entry: ProfileEntry,
  profile: BuildProfile,
): boolean {
  return entryBody === renderProfileEntry(entry, profile);
}

