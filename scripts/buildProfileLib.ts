export function parseTurbopackChunkRefs(routeJs: string): string[] {
  const refs: string[] = [];
  for (const m of routeJs.matchAll(/R\.c\(\s*["']([^"']+)["']\s*\)/g)) {
    refs.push(m[1]!);
  }
  return refs;
}

export function resolveCompiledRouteJs(root: string, sourceRouteEntry: string): string | undefined {
  // source: src/app/(backend)/.../route.ts
  // compiled: .next/server/app/(backend)/.../route.js
  const rel = sourceRouteEntry.replace(/^src\/app\//, '').replace(/route\.ts$/, 'route.js');
  const candidates = [
    path.join(root, '.next/server/app', rel),
    path.join(root, '.next/standalone/.next/server/app', rel),
  ];
  return candidates.find((p) => fs.existsSync(p));
}

/**
 * Turbopack R.c("server/chunks/foo.js") is relative to the Next dist root
 * (.next / .next/standalone/.next), NOT to .next/server.
 */
export function resolveTurbopackChunk(
  root: string,
  ref: string,
  routeJsPath?: string,
): string | undefined {
  const bases = new Set<string>();
  // Prefer dist root inferred from the compiled route.js path
  if (routeJsPath) {
    const marker = `${path.sep}.next${path.sep}server${path.sep}`;
    const idx = routeJsPath.lastIndexOf(marker);
    if (idx !== -1) {
      bases.add(routeJsPath.slice(0, idx + `${path.sep}.next`.length));
    }
  }
  bases.add(path.join(root, '.next'));
  bases.add(path.join(root, '.next/standalone/.next'));

  for (const base of bases) {
    const abs = path.join(base, ref);
    if (fs.existsSync(abs)) return abs;
  }
  return undefined;
}

export type ChunkCollection = {
  graph: string;
  refs: string[];
  missingRefs: string[];
  resolvedPaths: string[];
};

export function collectChunkSources(root: string, routeJsPath: string): ChunkCollection {
  const routeJs = fs.readFileSync(routeJsPath, 'utf8');
  const refs = parseTurbopackChunkRefs(routeJs);
  const parts = [routeJs];
  const missingRefs: string[] = [];
  const resolvedPaths: string[] = [];

  for (const ref of refs) {
    const abs = resolveTurbopackChunk(root, ref, routeJsPath);
    if (!abs) {
      missingRefs.push(ref);
      continue;
    }
    resolvedPaths.push(abs);
    parts.push(fs.readFileSync(abs, 'utf8'));
  }

  return {
    graph: parts.join('\n'),
    refs,
    missingRefs,
    resolvedPaths,
  };
}
